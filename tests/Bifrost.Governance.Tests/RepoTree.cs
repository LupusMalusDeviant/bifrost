using System.Text.RegularExpressions;

namespace Bifrost.Governance.Tests;

/// <summary>
/// Der Blick auf das Repository als <b>Dateibaum</b>, nicht als Programm.
/// <para>
/// Die Wächter in diesem Projekt prüfen Regeln über dem Code: ob ein Tor abgeschaltet ist, ob eine
/// Unterdrückung begründet wurde. Das steht in Textdateien und nicht in Typen — deshalb hat dieses
/// Projekt bewusst <b>keine Referenz auf das Produkt</b>. Eine Referenz brächte nichts und würde
/// die Prüfung an die Übersetzbarkeit dessen binden, was sie beurteilen soll.
/// </para>
/// </summary>
internal static class RepoTree
{
    /// <summary>
    /// Generierter Code folgt nicht denselben Regeln — und soll es nicht.
    /// <para>
    /// EF schreibt in jede Migrationsdatei <c>#pragma warning disable 612, 618</c> ohne Kommentar.
    /// Diese Zeilen als Verstoß zu zählen hieße, entweder generierten Code von Hand
    /// nachzubearbeiten (er wird beim nächsten Lauf überschrieben) oder den Wächter dauerhaft rot
    /// zu lassen. Beides macht ihn wertlos.
    /// </para>
    /// </summary>
    public static bool IsGenerated(string path, string content)
        => path.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase)
            || content.AsSpan(0, Math.Min(400, content.Length)).Contains("<auto-generated", StringComparison.Ordinal);

    public static string Root { get; } = Find();

    /// <summary>Alle C#-Dateien des Repositories ohne Build-Ausgaben.</summary>
    public static IEnumerable<(string Path, string Content)> CSharpFiles(params string[] relativeRoots)
    {
        foreach (var relative in relativeRoots)
        {
            var directory = Path.Combine(Root, relative);
            if (!Directory.Exists(directory))
            {
                continue;
            }

            foreach (var file in Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories))
            {
                if (IsBuildOutput(file))
                {
                    continue;
                }

                yield return (Relative(file), File.ReadAllText(file));
            }
        }
    }

    public static IEnumerable<(string Path, string Content)> Files(string relativeRoot, string pattern)
    {
        var directory = Path.Combine(Root, relativeRoot);
        if (!Directory.Exists(directory))
        {
            yield break;
        }

        foreach (var file in Directory.EnumerateFiles(directory, pattern, SearchOption.AllDirectories))
        {
            if (!IsBuildOutput(file))
            {
                yield return (Relative(file), File.ReadAllText(file));
            }
        }
    }

    public static string Relative(string absolute)
        => Path.GetRelativePath(Root, absolute).Replace('\\', '/');

    private static bool IsBuildOutput(string path)
    {
        var normalised = path.Replace('\\', '/');
        return normalised.Contains("/bin/", StringComparison.Ordinal)
            || normalised.Contains("/obj/", StringComparison.Ordinal);
    }

    /// <summary>
    /// Die Wurzel wird <b>gesucht</b>, nicht aus einer Konstanten abgeleitet: Der Testlauf startet
    /// in einem <c>bin</c>-Verzeichnis, dessen Tiefe sich mit jeder Umstellung ändert.
    /// </summary>
    private static string Find()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Bifrost.slnx")))
            {
                return directory.FullName;
            }

            directory = directory.Parent;
        }

        throw new InvalidOperationException(
            $"Keine Repository-Wurzel über {AppContext.BaseDirectory} gefunden (gesucht: Bifrost.slnx).");
    }

    /// <summary>
    /// Eine Kommentarzeile ist kein Verstoß — auch dann nicht, wenn sie den Verstoß beschreibt.
    /// <para>
    /// <b>Der erste Lauf dieses Wächters ist genau darüber gestolpert:</b> Der einzige Fund war der
    /// Kommentar, der die Regel erklärt. Ein Prüfer, der das Reden über eine Regel bestraft, sorgt
    /// dafür, dass niemand mehr darüber schreibt — und das ist das Gegenteil dessen, was er soll.
    /// </para>
    /// </summary>
    internal static bool IsProse(string line)
    {
        var trimmed = line.TrimStart();
        return trimmed.StartsWith("//", StringComparison.Ordinal)
            || trimmed.StartsWith('*')
            || trimmed.StartsWith("<!--", StringComparison.Ordinal);
    }
}

/// <summary>Ein Fund des Wächters — Datei, Zeile und was daran nicht stimmt.</summary>
internal sealed record Violation(string Path, int Line, string Text)
{
    public override string ToString() => $"{Path}:{Line}  {Text.Trim()}";
}

internal static class LineScanner
{
    /// <summary>
    /// Sucht Zeilen und liefert sie mit ihrer Nummer. Die Nummer ist kein Schmuck: Ein Wächter, der
    /// nur „irgendwo im Repository" meldet, wird nicht befolgt, sondern umgangen.
    /// </summary>
    public static IEnumerable<Violation> Scan(
        IEnumerable<(string Path, string Content)> files, Regex pattern, Func<string[], int, bool> isAllowed)
    {
        foreach (var (path, content) in files)
        {
            var lines = content.Split('\n');
            for (var i = 0; i < lines.Length; i++)
            {
                if (RepoTree.IsProse(lines[i]))
                {
                    continue;
                }

                if (pattern.IsMatch(lines[i]) && !isAllowed(lines, i))
                {
                    yield return new Violation(path, i + 1, lines[i]);
                }
            }
        }
    }
}
